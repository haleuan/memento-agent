"""Schemas for Memento record envelopes and shared types."""

from datetime import datetime
from typing import Annotated, Generic, Literal, TypeVar

from pydantic import (
    AfterValidator,
    BaseModel,
    ConfigDict,
    Field,
    StrictInt,
    StrictStr,
    field_validator,
)
from pydantic.types import StringConstraints

from .types import PartialDate

_HASH_PATTERN = r"^sha256:[0-9a-f]{64}$"

_RECORD_ID_PATTERN = r"^[a-z][a-z0-9-]*_[0-7][0-9A-HJKMNP-TV-Z]{25}$"

_SCHEMA_VERSION_PATTERN = r"^[a-z][a-z0-9-]*/[1-9][0-9]*$"


HashId = Annotated[
    StrictStr,
    StringConstraints(pattern=_HASH_PATTERN),
    Field(
        description="Content-addressed identifier for a source file in the format 'sha256:<hex>'. "
        "Example: 'sha256:a1b2c3d4...'"
    ),
]

RecordId = Annotated[
    StrictStr,
    StringConstraints(pattern=_RECORD_ID_PATTERN),
    Field(
        description="Unique record identifier in the format '<type>_<ULID>'. "
        "Example: 'ach_01JBX7Q3M8K2N5R9V4W6Y0ZDEF'. "
        "The ULID component is time-sortable and collision-resistant across multiple writers."
    ),
]

SchemaVersion = Annotated[
    StrictStr,
    StringConstraints(pattern=_SCHEMA_VERSION_PATTERN),
    Field(
        description="Schema version in the format '<type>/<version>'. "
        "Example: 'achievement/1', 'note/2'. "
        "Each record type maintains its own version sequence."
    ),
]


def _validate_timestamp(value: str) -> str:
    """Validate a timezone-aware ISO 8601 timestamp.

    Timestamps are generated by the system rather than interpreted from
    user-facing experience descriptions, so they use a stricter contract.

    The original string is preserved instead of being converted to a
    datetime object. This keeps serialization predictable and avoids
    timezone conversion issues.
    """
    try:
        parsed = datetime.fromisoformat(value)
    except ValueError as error:
        raise ValueError("must be an ISO 8601 timestamp with timezone") from error

    if "T" not in value:
        raise ValueError("must be an ISO 8601 timestamp with timezone")

    if parsed.tzinfo is None or parsed.utcoffset() is None:
        raise ValueError("must be an ISO 8601 timestamp with timezone")

    return value


Timestamp = Annotated[
    StrictStr,
    AfterValidator(_validate_timestamp),
    Field(
        description="System-generated timestamp in ISO 8601 format with timezone. "
        "Example: '2025-01-12T09:30:00+08:00'. "
        "This records when the system created or verified the record, "
        "not when the underlying event occurred."
    ),
]


class TimeRange(BaseModel):
    """A time range with optional start and end dates.

    Used for the 'occurred' field in the envelope to record when an experience
    took place in the real world.

    For instantaneous events (awards, paper publication), only 'start' is meaningful.
    For ongoing experiences (projects, internships), both 'start' and 'end' may be set.

    The agent should extract date strings from the source document and pass them
    to a deterministic date parser, which produces PartialDate objects. The agent
    should NOT guess missing dates or fill in incomplete information.
    """

    model_config = ConfigDict(extra="forbid")

    start: PartialDate | None = Field(
        default=None,
        description="When the experience began or when an instantaneous event occurred. "
        "For awards, this is typically the competition or award date. "
        "For papers, this is the publication or acceptance date. "
        "For ongoing work, this is the start date.",
    )
    end: PartialDate | None = Field(
        default=None,
        description="When the experience ended. Only applicable for ongoing experiences "
        "like projects, internships, or employment. Leave null for instantaneous events.",
    )


class Evidence(BaseModel):
    """A reference to a source document that supports claims in this record.

    Evidence links a record to the physical documents (certificates, papers,
    screenshots) that verify its claims. Each piece of evidence points to a
    source file by its content hash and optionally quotes specific text.

    The 'supports' field declares which record fields this evidence backs up,
    enabling validation rules like "level_raw must have matching evidence".
    """

    model_config = ConfigDict(extra="forbid")

    source: HashId = Field(
        description="Content hash of the source file in the workspace sources/ directory. "
        "Format: 'sha256:<64 hex chars>'"
    )

    page: StrictInt | None = Field(
        default=None,
        ge=1,
        description="Human-readable page number where this evidence appears (1-indexed). "
        "For multi-page PDFs, this helps locate the relevant section quickly.",
    )

    quote: StrictStr | None = Field(
        default=None,
        description="Optional verbatim text from the source that provides context for locating supporting information. "
        "Current validation checks that the source exists and does not require quote matching against parse blocks.",
    )

    supports: list[StrictStr] = Field(
        default_factory=list,
        description="Dot-separated paths to the record fields this evidence backs up. "
        "Examples: ['data.title', 'data.issuer', 'data.level_raw']. "
        "Critical fields (like level_raw) should always have supporting evidence.",
    )

    @field_validator("quote")
    @classmethod
    def validate_quote(cls, value: str | None) -> str | None:
        """Reject a quote that is present but contains only whitespace."""
        if value is not None and not value.strip():
            raise ValueError("quote must contain non-whitespace text")
        return value


class Verification(BaseModel):
    """Human confirmation that a record has been reviewed and approved.

    In v1, this is purely metadata—it does not include cryptographic sealing
    or tamper detection. Those features may be added in future versions.
    """

    model_config = ConfigDict(extra="forbid")

    by: StrictStr = Field(
        min_length=1,
        description="Identifier of the person who verified this record. "
        "Could be a username, email, or system user ID.",
    )
    at: Timestamp = Field(
        description="When the verification occurred (system timestamp)."
    )


RecordData = TypeVar("RecordData", bound=BaseModel)


class RecordEnvelope(BaseModel, Generic[RecordData]):
    """Common structure shared by all Memento records.

    The envelope contains metadata and lifecycle information that applies to
    all record types (achievements, notes, tasks, preferences, etc.). The
    type-specific content lives in the 'data' field.

    Generic usage:
        - RecordEnvelope[AchievementItem] for achievement records
        - RecordEnvelope[NoteData] for note records (future)
        - RecordEnvelope[TaskData] for task records (future)

    The envelope handles concerns like:
        - Identity (id)
        - Schema versioning (schema_version)
        - Provenance tracking (provenance, created_at)
        - Time information (occurred)
        - Evidence links (evidence)
        - Human verification (verification)
    """

    model_config = ConfigDict(
        extra="forbid",
        populate_by_name=True,
    )

    id: RecordId = Field(
        description="Unique identifier for this record. Format: '<type>_<ULID>'. "
        "Generated once at record creation and never changed."
    )

    schema_version: SchemaVersion = Field(
        alias="schema",
        description="Schema version for the 'data' payload. Format: '<type>/<version>'. "
        "Each record type (achievement, note, task) has its own version counter. "
        "This field uses the alias 'schema' in serialized TOML to avoid colliding "
        "with Python/Pydantic's schema-related APIs.",
    )

    provenance: Literal["document", "user", "agent"] = Field(
        description=(
            "Source of this record's information:\n"
            "- 'document': Extracted from a certificate, paper, or other verifiable source\n"
            "- 'user': Directly entered by the user (no supporting document)\n"
            "- 'agent': Generated by the AI agent (must be verified before use)"
        )
    )

    created_at: Timestamp = Field(
        description="When this record was created in the Memento workspace (system time). "
        "This is NOT when the underlying event occurred—see 'occurred' for that."
    )

    occurred: TimeRange | None = Field(
        default=None,
        description="When the underlying experience happened in the real world. "
        "For awards, this is when you received the award. "
        "For papers, this is the publication date. "
        "For projects/internships, this is the start and end dates. "
        "May be null for record types that don't have a meaningful occurrence time "
        "(e.g., preferences, evergreen notes).",
    )

    data: RecordData = Field(
        description="Type-specific structured payload. For achievement records, this is AchievementItem. "
        "For future record types (notes, tasks), this will be their respective data classes."
    )

    evidence: list[Evidence] = Field(
        default_factory=list,
        description="Supporting documents that verify claims in this record. "
        "For provenance='document', at least one evidence entry is expected. "
        "For provenance='user', evidence may be empty if the user is self-reporting. "
        "For provenance='agent', evidence should cite the source records the agent used.",
    )

    verification: Verification | None = Field(
        default=None,
        description="Optional human confirmation that this record has been reviewed. "
        "Null means the record is unverified (draft state). "
        "Setting this field typically requires an interactive CLI command rather than "
        "being freely writable by agents.",
    )
